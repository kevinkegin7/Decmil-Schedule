create or replace function public.fn_normalize_employer_name()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.normalized_name := regexp_replace(
    regexp_replace(lower(btrim(new.name)), '[^a-z0-9]+', ' ', 'g'),
    '\s+(inc|llc|ltd|corp|corporation|co|company|plc|lp|llp)\s*$', '');
  new.normalized_name := btrim(new.normalized_name);
  return new;
end $$;

