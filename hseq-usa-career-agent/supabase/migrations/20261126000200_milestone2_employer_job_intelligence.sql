create table public.sponsorship_evidence (
  id             uuid primary key default gen_random_uuid(),
  user_id        uuid not null references auth.users (id) on delete cascade,
  is_sample      boolean not null default false,
  employer_id    uuid not null references public.employers (id) on delete cascade,
  job_id         uuid references public.job_opportunities (id) on delete cascade,
  evidence_type  text not null check (evidence_type in (
                   'written_confirmation',        -- employer confirmed in writing to the user
                   'official_posting_offers',     -- employer's own posting says sponsorship available
                   'official_policy_offers',      -- employer's official careers/policy page says so
                   'official_posting_declines',   -- employer's own posting says no sponsorship
                   'official_policy_declines',
                   'dol_lca_history',             -- past LCA filings (H-1B / E-3)
                   'dol_perm_history',            -- past PERM labour certifications
                   'uscis_h1b_history')),         -- past H-1B petition decisions
  category       text generated always as (
                   case
                     when evidence_type in ('written_confirmation','official_posting_offers','official_policy_offers') then 'confirmed'
                     when evidence_type in ('official_posting_declines','official_policy_declines') then 'explicit_no'
                     else 'historical'
                   end) stored,
  visa_classes   text[] not null default '{}',
  fiscal_year    int check (fiscal_year between 2000 and 2100),
  filing_count   int check (filing_count >= 0),
  soc_codes      text[] not null default '{}',
  source         text not null references public.data_sources (code),
  source_url     text check (source_url is null or source_url ~ '^https?://'),
  source_title   text,
  excerpt        text check (char_length(excerpt) <= 2000),
  retrieved_at   timestamptz not null,
  verified_at    timestamptz,
  verified_by    text check (verified_by in ('user','system')),
  confidence     text not null check (confidence in ('high','medium','low')),
  notes          text check (char_length(notes) <= 2000),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  constraint url_unless_written check (evidence_type = 'written_confirmation' or source_url is not null),
  constraint written_confirmation_is_user_verified check (
    evidence_type <> 'written_confirmation' or (verified_by = 'user' and verified_at is not null)),
  constraint verified_pair check ((verified_at is null) = (verified_by is null)),
  constraint history_has_year check (
    evidence_type not in ('dol_lca_history','dol_perm_history','uscis_h1b_history') or fiscal_year is not null)
);
