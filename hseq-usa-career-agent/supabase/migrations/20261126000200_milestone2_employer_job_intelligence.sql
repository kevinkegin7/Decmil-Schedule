-- Cross-table ownership: a user's job, evidence or save must point at their own employer/job.
create or replace function public.fn_assert_same_owner()
returns trigger language plpgsql set search_path = '' as $$
-- Nested IFs on purpose: each branch only touches columns its own table has.
begin
  if tg_table_name in ('job_opportunities','sponsorship_evidence','saved_employers') then
    if not exists (select 1 from public.employers e where e.id = new.employer_id and e.user_id = new.user_id) then
      raise exception 'employer does not belong to this user';
    end if;
  end if;
  if tg_table_name = 'sponsorship_evidence' then
    if new.job_id is not null then
      if not exists (select 1 from public.job_opportunities j
                      where j.id = new.job_id and j.user_id = new.user_id and j.employer_id = new.employer_id) then
        raise exception 'job does not belong to this employer and user';
      end if;
    end if;
  end if;
  if tg_table_name in ('saved_jobs','job_matches') then
    if not exists (select 1 from public.job_opportunities j where j.id = new.job_id and j.user_id = new.user_id) then
      raise exception 'job does not belong to this user';
    end if;
  end if;
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['job_opportunities','sponsorship_evidence','saved_employers','saved_jobs','job_matches'] loop
    execute format('create trigger trg_same_owner before insert or update on public.%I
                    for each row execute function public.fn_assert_same_owner()', t);
  end loop;
end $$;

